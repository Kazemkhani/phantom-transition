"""Render the matrix as Markdown and LaTeX, and the manifest that makes it reproducible."""

from __future__ import annotations

from typing import Sequence

from .protocol import CONFIGS, NotMeasured, Summary

Cell = Summary | NotMeasured


def _cell_text(cell: Cell, *, tex: bool = False) -> str:
    if isinstance(cell, NotMeasured):
        return "not measured"
    v = cell.verdict
    if v == "committed":
        body = f"committed {cell.committed}/{cell.n}"
    elif v == "cancelled":
        body = f"cancelled {cell.cancelled}/{cell.n}"
    elif v == "race-dependent":
        body = f"race-dependent, committed {cell.committed}/{cell.n} ({cell.rate:.0%})"
    else:
        body = f"{v} ({cell.committed}/{cell.n} committed)"
    if cell.barge_in_suppressed:
        body += f"; barge-in suppressed {cell.barge_in_suppressed}/{cell.n}"
    if cell.handoff_applied is not None:
        body += f"; handoff applied {cell.handoff_applied}/{cell.n}"
    return body


def _rows(cells: Sequence[Cell]) -> list[tuple[str, str, dict[str, Cell]]]:
    by_runtime: dict[tuple[str, str], dict[str, Cell]] = {}
    for c in cells:
        by_runtime.setdefault((c.runtime, c.runtime_version), {})[c.config] = c
    return [(rt, ver, cfgs) for (rt, ver), cfgs in by_runtime.items()]


def render_matrix_md(
    cells: Sequence[Cell], *, seed: int, n: int, commit: str, extra_notes: Sequence[str] = ()
) -> str:
    cfg_names = [c.name for c in CONFIGS]
    lines = [
        "# Cross-framework matrix: does a state-mutating tool call survive a barge-in?",
        "",
        f"Seed {seed}, N = {n} runs per cell, commit `{commit}`. Every number below was "
        "produced by `python experiments/frameworks/run_matrix.py`; the raw per-run "
        "records are in `results/frameworks/raw/`.",
        "",
        "Cell vocabulary: `committed` (the phase advanced on every run), `cancelled` (the phase "
        "never advanced), `race-dependent` (some runs committed, rate given), `not measured` "
        "(the reason is listed below the table; a blank is never a guess).",
        "",
        "| Runtime | Version | " + " | ".join(cfg_names) + " |",
        "|---|---|" + "|".join("---" for _ in cfg_names) + "|",
    ]
    prelude_notes = list(extra_notes)
    for rt, ver, cfgs in _rows(cells):
        row = [rt, ver]
        for name in cfg_names:
            cell = cfgs.get(name)
            row.append(_cell_text(cell) if cell is not None else "not measured")
        lines.append("| " + " | ".join(row) + " |")

    if prelude_notes:
        lines += [""]
        for note in prelude_notes:
            lines.append(note)

    lines += ["", "## Configurations", ""]
    for c in CONFIGS:
        lines.append(f"- `{c.name}`: {c.description}.")

    lines += ["", "## Mechanism per cell", ""]
    for c in cells:
        if isinstance(c, Summary) and c.mechanism:
            lines.append(f"- {c.runtime} {c.runtime_version}, `{c.config}`: {c.mechanism}")

    nm = [c for c in cells if isinstance(c, NotMeasured)]
    if nm:
        lines += ["", "## Not measured", ""]
        for c in nm:
            lines.append(f"- {c.runtime} {c.runtime_version}, `{c.config}`: {c.reason}")

    lines += ["", "## Per-cell detail", ""]
    lines.append(
        "| Runtime | Version | Config | N | committed | cancelled | tool finished | "
        "tool record kept | barge-in suppressed | handoff applied |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for c in cells:
        if isinstance(c, Summary):
            kept = "n/a" if c.tool_record_kept is None else str(c.tool_record_kept)
            handoff = "n/a" if c.handoff_applied is None else str(c.handoff_applied)
            lines.append(
                f"| {c.runtime} | {c.runtime_version} | {c.config} | {c.n} | {c.committed} | "
                f"{c.cancelled} | {c.tool_finished} | {kept} | {c.barge_in_suppressed} | "
                f"{handoff} |"
            )
    return "\n".join(lines) + "\n"


def _tex_escape(s: str) -> str:
    return (
        s.replace("\\", "\\textbackslash{}")
        .replace("_", "\\_")
        .replace("%", "\\%")
        .replace("&", "\\&")
        .replace("#", "\\#")
    )


def render_matrix_tex(cells: Sequence[Cell], *, seed: int, n: int, commit: str) -> str:
    cfg_names = [c.name for c in CONFIGS]
    cols = "ll" + "l" * len(cfg_names)
    lines = [
        "% Generated by experiments/frameworks/run_matrix.py. Do not edit by hand.",
        f"% seed={seed} n={n} commit={commit}",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\begin{tabular}{" + cols + "}",
        "\\toprule",
        "Runtime & Version & " + " & ".join(_tex_escape(c) for c in cfg_names) + " \\\\",
        "\\midrule",
    ]
    for rt, ver, cfgs in _rows(cells):
        row = [_tex_escape(rt), _tex_escape(ver)]
        for name in cfg_names:
            cell = cfgs.get(name)
            row.append(_tex_escape(_cell_text(cell) if cell is not None else "not measured"))
        lines.append(" & ".join(row) + " \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Whether a state-mutating tool call issued during an agent turn survives a "
        f"barge-in, per runtime and configuration. N={n} seeded runs per cell (seed {seed}). "
        "``committed'' means the phase advanced on every run; ``cancelled'' means it never did; "
        "``not measured'' cells are explained in the supplementary material.}",
        "\\label{tab:framework-matrix}",
        "\\end{table}",
    ]
    return "\n".join(lines) + "\n"


def render_manifest(
    *,
    commit: str,
    seed: int,
    n: int,
    commands: Sequence[str],
    environments: Sequence[tuple[str, str, str]],
    machine: str,
    started: str,
    finished: str,
) -> str:
    lines = [
        "# MANIFEST: cross-framework matrix",
        "",
        f"- Repository commit: `{commit}`",
        f"- Seed: `{seed}`",
        f"- N per cell: `{n}`",
        f"- Machine: {machine}",
        f"- Started: {started}",
        f"- Finished: {finished}",
        "",
        "## Commands",
        "",
    ]
    for cmd in commands:
        lines.append(f"    {cmd}")
    lines += ["", "## Environments (`pip freeze` per venv)", ""]
    for label, python, freeze in environments:
        lines += [f"### {label}", "", f"Interpreter: `{python}`", "", "```", freeze.rstrip(), "```", ""]
    return "\n".join(lines) + "\n"
